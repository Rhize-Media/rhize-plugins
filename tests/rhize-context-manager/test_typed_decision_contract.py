def load(name):
    return json.loads((FIX / name).read_text(encoding='utf-8'))


@pytest.mark.parametrize('case', load('laya-choice-requests.json')['cases'], ids=lambda c: c['name'])
def test_request_builder_matches_fixture(case):
    built = instrument.build_choice_request(case['prompt'], case['candidates'])
    expected = case['expected']
    assert instrument.canonical_json(built['request']) == expected['canonicalRequest']
    assert built['keyMap'] == expected['keyMap']
    assert built['truncated'] is expected['truncated']
    assert built['promptLengthBucket'] == expected['promptLengthBucket']
    assert built['criteriaSha256'] == expected['criteriaSha256']
    assert built['instrumentSha256'] == expected['instrumentSha256']


def test_prompt_head_stays_within_codepoint_cap():
    for case in load('laya-choice-requests.json')['cases']:
        head = json.loads(case['expected']['canonicalRequest'])['state']['request']
        assert len(head) <= instrument.PROMPT_HEAD_CODEPOINTS
        if case['expected']['truncated']:
            assert case['prompt'].startswith(head)
            assert head == head.rstrip(instrument.ASCII_WS)


