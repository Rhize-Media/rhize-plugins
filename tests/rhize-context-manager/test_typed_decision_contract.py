def test_identities():
    data = load('identities.json')
    assert contract.policy_sha256('cosign-v1') == data['policySha256']['cosign-v1']
    assert instrument.instrument_sha256() == data['instrumentSha256']
    for case in data['occurrenceKeys']:
        assert contract.occurrence_key(case['sessionHash'], case['promptHash'], case['ts']) == case['expected']
    for case in data['arms']:
        assert contract.arm_for(case['sessionHash'], case['promptHash'], case['holdback']) == case['expected']
    holdback = sum(1 for c in data['arms'] if c['holdback'] == 0.5 and c['expected'] == 'holdback')
    assert 8 <= holdback <= 32  # 40 draws at p=0.5: sanity bound on the bucket arithmetic
    assert all(c['expected'] == 'treatment' for c in data['arms'] if c['holdback'] == 0)


def test_occurrence_key_is_minute_scoped_and_offset_aware():
    data = load('identities.json')['occurrenceKeys']
