@pytest.mark.skipif(jsonschema is None, reason='jsonschema not installed; stdlib validators are canonical')
def test_json_schemas_accept_valid_fixtures():
    def schema(name):
        return json.loads((SCHEMAS / f'{name}.schema.json').read_text())
    pairs = [('typed-decision-record-v1', load('records.json')['valid'].values()),
             ('typed-decision-label-v1', load('labels.json')['valid'].values()),
             ('typed-decision-outcome-v1', load('outcomes.json')['valid'].values()),
             ('typed-decision-cohort-v1', load('cohorts.json')['valid'].values()),
             ('decision-registry-state-v1', load('registry.json')['validStates'].values()),
             ('decision-registry-audit-v1', load('registry.json')['validAudit'].values()),
             ('decision-registry-v1', [json.loads((REPO / 'rhize-context-manager' / 'catalog' / 'decision-registry.json').read_text())])]
    for name, values in pairs:
        validator = jsonschema.Draft202012Validator(schema(name))
        for value in values:
            validator.validate(value)
    critical = [c['registry'] for c in load('registry.json')['invalidRegistries'] if c['name'] == 'critical-cosign']
    with pytest.raises(jsonschema.ValidationError):
        jsonschema.Draft202012Validator(schema('decision-registry-v1')).validate(critical[0])
    # Named decision constraints must retain the common required shape, not bypass additionalProperties.
    shipped = json.loads((REPO / 'rhize-context-manager/catalog/decision-registry.json').read_text())
    registry_validator = jsonschema.Draft202012Validator(schema('decision-registry-v1'))
    for field in ('tier', 'gates', 'model'):
        broken = json.loads(json.dumps(shipped))
        del broken['decisions']['workflow-fit'][field]
        with pytest.raises(jsonschema.ValidationError): registry_validator.validate(broken)
    state = json.loads(json.dumps(load('registry.json')['validStates']['cosign']))
    entry = state['decisions'].pop('skill-fit')
    entry.update(layaRevision='fixture-known', cohortId=None,
                 policySha256=contract.policy_sha256(contract.POLICY_CREDENTIAL),
                 instrumentSha256=instrument.instrument_sha256(contract.POLICY_CREDENTIAL))
    state['decisions']['workflow-fit'] = entry
    state_validator = jsonschema.Draft202012Validator(schema('decision-registry-state-v1'))
    state_validator.validate(state)
    for field, value in [('layaRevision', None), ('layaRevision', 'unknown'), ('cohortId', 'a' * 32),
                         ('policySha256', None)]:
        broken = json.loads(json.dumps(state)); broken['decisions']['workflow-fit'][field] = value
        with pytest.raises(jsonschema.ValidationError): state_validator.validate(broken)


def test_records_storage_roundtrip(tmp_path):
    import os
    import stat
    from typed_decisions import records as store
    data = load('records.json')['valid']
    path = store.append(tmp_path, 'skill-fit', 'records', data['live-shadow-agree'])
    store.append(tmp_path, 'skill-fit', 'records', data['live-shadow-agree'])
    store.append(tmp_path, 'skill-fit', 'records', data['backfill-silent-skipped'])
    assert path.name == '2026-10-11.jsonl'
    assert stat.S_IMODE(os.stat(path).st_mode) == 0o600
    assert stat.S_IMODE(os.stat(path.parent).st_mode) == 0o700
    with open(path, 'a', encoding='utf-8') as stream:
        stream.write('{"not": "a record"}\n')
    items, invalid = store.read(tmp_path, 'skill-fit', 'records')
    assert len(items) == 3 and invalid == 1
    # All three fixture records share session, prompt and minute: one occurrence.
    assert len(store.dedupe_by_occurrence(items)) == 1
    with pytest.raises(ValueError):
        store.append(tmp_path, 'skill-fit', 'records', {**data['live-shadow-agree'], 'prompt': 'x'})
    assert store.read(tmp_path, 'skill-fit', 'labels') == ([], 0)


